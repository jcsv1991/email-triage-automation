#!/usr/bin/env node
// Builds workflow/email-triage.workflow.json, the file you import into n8n.
//
// The logic that matters (sanitizing, validating, Slack text) lives in src/*.js where it
// is unit-tested. n8n Code nodes cannot import local files, so this script inlines those
// exact sources into the Code nodes. That way the code that is tested is the code that runs.
//
//   node scripts/build-workflow.mjs           write the workflow file
//   node scripts/build-workflow.mjs --check   fail if the committed file is out of date

import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (rel) => readFileSync(path.join(root, rel), 'utf8');
const OUT = 'workflow/email-triage.workflow.json';

// ---------------------------------------------------------------- source modules
function moduleSource(rel) {
  const src = read(rel);
  const stripped = src.replace(/\nexport \{[^}]*\};?\s*$/, '\n');
  if (/^\s*export\s/m.test(stripped) || /^\s*import\s/m.test(stripped)) {
    throw new Error(`${rel} must not contain import/export statements outside the final export list`);
  }
  return `// ---- ${rel} ----\n${stripped.trim()}\n`;
}

const SANITIZE = moduleSource('src/sanitize.js');
const VALIDATE = moduleSource('src/validate.js');
const HELPERS = moduleSource('src/helpers.js');
const SYSTEM_PROMPT = read('prompts/system-prompt.txt').trim();
const TRIAGE_TOOL = JSON.parse(read('schema/triage_email.tool.json'));

const HEADER =
  '// AUTO-GENERATED by scripts/build-workflow.mjs from the files in src/.\n' +
  '// Edit the source files and run `npm run build` instead of editing this node.\n';

// ---------------------------------------------------------------- helpers
const uuid = (seed) => {
  const h = createHash('sha1').update('email-triage-automation:' + seed).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};

const nodes = [];
const connections = {};

function addNode(name, type, typeVersion, position, parameters, extra = {}) {
  nodes.push({ parameters, id: uuid(name), name, type, typeVersion, position, ...extra });
}

function connect(from, to, outputIndex = 0) {
  connections[from] = connections[from] || { main: [] };
  const main = connections[from].main;
  while (main.length <= outputIndex) main.push([]);
  main[outputIndex].push({ node: to, type: 'main', index: 0 });
}

function codeNode(name, position, mode, modules, glue, extra = {}) {
  const jsCode = HEADER + '\n' + modules.join('\n') + '\n// ---- node logic ----\n' + glue.trim() + '\n';
  addNode(name, 'n8n-nodes-base.code', 2, position, { mode, jsCode }, extra);
}

function note(name, position, width, height, color, content) {
  addNode(name, 'n8n-nodes-base.stickyNote', 1, position, { content, height, width, color });
}

const gmailCred = { gmailOAuth2: { id: 'REPLACE_ME', name: 'Gmail account' } };
const sheetsCred = { googleSheetsOAuth2Api: { id: 'REPLACE_ME', name: 'Google Sheets account' } };
const slackCred = { slackApi: { id: 'REPLACE_ME', name: 'Slack bot token' } };
const anthropicCred = { httpHeaderAuth: { id: 'REPLACE_ME', name: 'Anthropic API key' } };

const slackPost = (text) => ({
  authentication: 'accessToken',
  select: 'channel',
  channelId: { __rl: true, value: '#support-alerts', mode: 'name' },
  text,
  otherOptions: { includeLinkToWorkflow: false },
});

const SHEET_COLUMNS = [
  ['Received', '={{ $json.receivedAt }}'],
  ['From', '={{ $json.from }}'],
  ['Subject', '={{ $json.subject }}'],
  ['Category', '={{ $json.triage.category }}'],
  ['Urgency', '={{ $json.triage.urgency }}'],
  ['Summary', '={{ $json.triage.summary }}'],
  ['Flags', "={{ $json.clean.signals.join(', ') }}"],
  ['Thread ID', '={{ $json.threadId }}'],
];

// ---------------------------------------------------------------- nodes
const X = 220;
const col = (n) => n * X;

addNode('Gmail Trigger', 'n8n-nodes-base.gmailTrigger', 1.3, [col(0), 300], {
  pollTimes: { item: [{ mode: 'everyMinute' }] },
  simple: false,
  filters: { q: 'in:inbox', readStatus: 'unread' },
  options: {},
}, { credentials: gmailCred });

addNode('Settings', 'n8n-nodes-base.set', 3.4, [col(1), 300], {
  assignments: {
    assignments: [
      { id: uuid('set-model'), name: 'model', value: 'claude-haiku-4-5-20251001', type: 'string' },
      { id: uuid('set-maxTokens'), name: 'maxTokens', value: 1024, type: 'number' },
      { id: uuid('set-maxBodyChars'), name: 'maxBodyChars', value: 4000, type: 'number' },
      { id: uuid('set-labelPrefix'), name: 'labelPrefix', value: 'Triage/', type: 'string' },
      { id: uuid('set-mailIndex'), name: 'mailIndex', value: 0, type: 'number' },
    ],
  },
  includeOtherFields: true,
  options: {},
});

codeNode('Sanitize email', [col(2), 300], 'runOnceForEachItem', [SANITIZE, HELPERS], `
const s = $json;
const clean = sanitizeEmail(s, { maxChars: Number(s.maxBodyChars) || 4000 });
return {
  json: {
    id: s.id,
    threadId: s.threadId,
    receivedAt: s.date || new Date().toISOString(),
    from: clean.from,
    fromName: clean.fromName,
    replyTo: firstAddress(s.replyTo) || clean.from,
    subject: clean.subject,
    clean: {
      userMessage: clean.userMessage,
      bodySource: clean.bodySource,
      signals: clean.signals,
      suspicious: clean.suspicious,
      stats: clean.stats,
    },
    settings: {
      model: s.model,
      maxTokens: Number(s.maxTokens) || 1024,
      labelPrefix: typeof s.labelPrefix === 'string' ? s.labelPrefix : 'Triage/',
      mailIndex: Number(s.mailIndex) || 0,
    },
  },
};
`);

codeNode('Build Claude request', [col(3), 300], 'runOnceForEachItem', [],
  `const SYSTEM_PROMPT = ${JSON.stringify(SYSTEM_PROMPT)};
const TRIAGE_TOOL = ${JSON.stringify(TRIAGE_TOOL, null, 2)};

// The model is forced to answer through the triage_email tool, so the reply always has
// the same four typed fields instead of free text that has to be parsed.
const { clean, settings } = $json;
return {
  json: {
    ...$json,
    request: {
      model: settings.model,
      max_tokens: settings.maxTokens,
      system: SYSTEM_PROMPT,
      messages: [{ role: 'user', content: clean.userMessage }],
      tools: [TRIAGE_TOOL],
      tool_choice: { type: 'tool', name: TRIAGE_TOOL.name },
    },
  },
};`);

addNode('Claude: classify + draft', 'n8n-nodes-base.httpRequest', 4.2, [col(4), 300], {
  method: 'POST',
  url: 'https://api.anthropic.com/v1/messages',
  authentication: 'genericCredentialType',
  genericAuthType: 'httpHeaderAuth',
  sendHeaders: true,
  headerParameters: { parameters: [{ name: 'anthropic-version', value: '2023-06-01' }] },
  sendBody: true,
  contentType: 'json',
  specifyBody: 'json',
  jsonBody: '={{ JSON.stringify($json.request) }}',
  options: { timeout: 60000 },
}, {
  credentials: anthropicCred,
  retryOnFail: true,
  maxTries: 3,
  waitBetweenTries: 3000,
  onError: 'continueRegularOutput',
});

codeNode('Validate triage', [col(5), 300], 'runOnceForEachItem', [VALIDATE],
  `const TRIAGE_SCHEMA = ${JSON.stringify(TRIAGE_TOOL)};

// $json is Claude's raw response (or the error that replaced it). Re-attach the email
// data from before the API call and check the answer; nothing downstream trusts it
// until it has passed.
const { request, ...email } = $('Build Claude request').item.json;
const result = validateTriage($json, TRIAGE_SCHEMA);
return {
  json: { ...email, valid: result.valid, errors: result.errors, triage: result.triage, usage: result.usage },
};`);

addNode('Schema valid?', 'n8n-nodes-base.if', 2.2, [col(6), 300], {
  conditions: {
    options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
    conditions: [{
      id: uuid('if-valid'),
      leftValue: '={{ $json.valid }}',
      rightValue: '',
      operator: { type: 'boolean', operation: 'true', singleValue: true },
    }],
    combinator: 'and',
  },
  options: {},
});

// ---- failure branch
codeNode('Format review alert', [col(7), 540], 'runOnceForEachItem', [HELPERS], `
const j = $json;
return {
  json: {
    ...j,
    text: formatReviewAlert({
      from: j.from, fromName: j.fromName, subject: j.subject, errors: j.errors,
      signals: j.clean.signals, threadId: j.threadId, mailIndex: j.settings.mailIndex,
    }),
  },
};
`);

addNode('Slack: manual review alert', 'n8n-nodes-base.slack', 2.3, [col(8), 540],
  slackPost('={{ $json.text }}'),
  { credentials: slackCred, retryOnFail: true, maxTries: 3, waitBetweenTries: 2000 });

// ---- success branch
addNode('Log to Google Sheets', 'n8n-nodes-base.googleSheets', 4.5, [col(7), 160], {
  operation: 'append',
  documentId: { __rl: true, value: 'REPLACE_WITH_SPREADSHEET_ID', mode: 'id' },
  sheetName: { __rl: true, value: 'Triage log', mode: 'name' },
  columns: {
    mappingMode: 'defineBelow',
    value: Object.fromEntries(SHEET_COLUMNS),
    matchingColumns: [],
    schema: SHEET_COLUMNS.map(([id]) => ({
      id, displayName: id, required: false, defaultMatch: false, display: true, type: 'string', canBeUsedToMatch: true,
    })),
    attemptToConvertTypes: false,
    convertFieldsToString: true,
  },
  options: {},
}, {
  credentials: sheetsCred,
  retryOnFail: true,
  maxTries: 2,
  waitBetweenTries: 2000,
  onError: 'continueRegularOutput',
});

addNode('Get Gmail labels', 'n8n-nodes-base.gmail', 2.1, [col(8), 160], {
  resource: 'label',
  operation: 'getAll',
  returnAll: true,
}, { credentials: gmailCred, executeOnce: true, onError: 'continueRegularOutput' });

codeNode('Resolve label ID', [col(9), 160], 'runOnceForAllItems', [HELPERS], `
// Gmail's API wants label IDs, not names. Match "<prefix><category>" against the account's labels.
const byName = new Map(
  $input.all().map((i) => i.json).filter((l) => l && l.name && l.id).map((l) => [String(l.name).toLowerCase(), l.id])
);
return $('Schema valid?').all(0).map((item, i) => {
  const j = item.json;
  const labelName = labelNameFor(j.settings.labelPrefix, j.triage.category);
  return {
    json: { ...j, labelName, labelId: byName.get(labelName.toLowerCase()) || '', replySubject: replySubject(j.subject) },
    pairedItem: { item: i },
  };
});
`);

addNode('Apply Gmail label', 'n8n-nodes-base.gmail', 2.1, [col(10), 160], {
  resource: 'message',
  operation: 'addLabels',
  messageId: '={{ $json.id }}',
  labelIds: '={{ $json.labelId ? [$json.labelId] : [] }}',
}, { credentials: gmailCred, onError: 'continueRegularOutput' });

addNode('Save Gmail draft', 'n8n-nodes-base.gmail', 2.1, [col(11), 160], {
  resource: 'draft',
  operation: 'create',
  subject: "={{ $('Resolve label ID').item.json.replySubject }}",
  emailType: 'text',
  message: "={{ $('Resolve label ID').item.json.triage.suggested_reply }}",
  options: {
    threadId: "={{ $('Resolve label ID').item.json.threadId }}",
    sendTo: "={{ $('Resolve label ID').item.json.replyTo }}",
  },
}, { credentials: gmailCred, retryOnFail: true, maxTries: 3, waitBetweenTries: 2000 });

addNode('Urgent?', 'n8n-nodes-base.if', 2.2, [col(12), 160], {
  conditions: {
    options: { caseSensitive: true, leftValue: '', typeValidation: 'strict', version: 2 },
    conditions: [{
      id: uuid('if-urgent'),
      leftValue: "={{ $('Resolve label ID').item.json.triage.urgency }}",
      rightValue: 'high',
      operator: { type: 'string', operation: 'equals' },
    }],
    combinator: 'and',
  },
  options: {},
});

codeNode('Format urgent alert', [col(13), 60], 'runOnceForEachItem', [HELPERS], `
// $json is the Gmail draft that was just saved; the triage data comes from before it.
const j = $('Resolve label ID').item.json;
return {
  json: {
    text: formatUrgentAlert({
      from: j.from, fromName: j.fromName, subject: j.subject, triage: j.triage,
      signals: j.clean.signals, threadId: j.threadId,
      draftMessageId: $json.message && $json.message.id, mailIndex: j.settings.mailIndex,
    }),
  },
};
`);

addNode('Slack: urgent alert', 'n8n-nodes-base.slack', 2.3, [col(14), 60],
  slackPost('={{ $json.text }}'),
  { credentials: slackCred, retryOnFail: true, maxTries: 3, waitBetweenTries: 2000 });

addNode('Done: draft waiting for review', 'n8n-nodes-base.noOp', 1, [col(15), 160], {});

// ---------------------------------------------------------------- notes
note('Note: setup', [-40, -160], 560, 300, 4,
  '## Set up in 5 steps\n' +
  '1. **Credentials:** connect Gmail (OAuth2), Google Sheets (OAuth2), Slack (bot token) and an Anthropic API key (Header Auth, name `x-api-key`).\n' +
  '2. **Gmail labels:** create `Triage/billing`, `Triage/technical`, `Triage/general`, `Triage/other`.\n' +
  '3. **Sheet:** create a tab called `Triage log` with the header row from `docs/triage-log-header.csv`; paste its ID into *Log to Google Sheets*.\n' +
  '4. **Slack:** pick the alert channel in both Slack nodes.\n' +
  '5. **Tune** model, body limit and label prefix in the *Settings* node, then activate.\n\n' +
  '**The model is never trusted blindly:** its answer is forced into a typed tool call, then validated again before anything is logged, labelled or drafted.');

note('Note: sanitize', [col(2) - 40, 460], 520, 150, 5,
  '## Before Claude sees anything\n' +
  'Strips HTML, hidden text, tracking pixels, quoted replies, signatures and footers, and caps length. Instruction-like text aimed at an AI is **flagged** for the reviewer, never obeyed.');

note('Note: never sends', [col(10) - 40, -120], 700, 140, 6,
  '## Nothing is ever sent\n' +
  'This workflow contains no Send or Reply node. The reply is saved as a **Gmail draft** on the original thread; a person reads it, edits it and presses send. Urgent emails also ping Slack with a link to that draft.');

// ---------------------------------------------------------------- wiring
connect('Gmail Trigger', 'Settings');
connect('Settings', 'Sanitize email');
connect('Sanitize email', 'Build Claude request');
connect('Build Claude request', 'Claude: classify + draft');
connect('Claude: classify + draft', 'Validate triage');
connect('Validate triage', 'Schema valid?');
connect('Schema valid?', 'Log to Google Sheets', 0);
connect('Schema valid?', 'Format review alert', 1);
connect('Format review alert', 'Slack: manual review alert');
connect('Log to Google Sheets', 'Get Gmail labels');
connect('Get Gmail labels', 'Resolve label ID');
connect('Resolve label ID', 'Apply Gmail label');
connect('Apply Gmail label', 'Save Gmail draft');
connect('Save Gmail draft', 'Urgent?');
connect('Urgent?', 'Format urgent alert', 0);
connect('Urgent?', 'Done: draft waiting for review', 1);
connect('Format urgent alert', 'Slack: urgent alert');
connect('Slack: urgent alert', 'Done: draft waiting for review');

const workflow = {
  name: 'Email triage: Claude classifies and drafts, a human sends',
  nodes,
  pinData: {},
  connections,
  active: false,
  settings: { executionOrder: 'v1' },
  meta: { templateCredsSetupCompleted: false },
};

const output = JSON.stringify(workflow, null, 2) + '\n';

if (process.argv.includes('--check')) {
  let current = '';
  try {
    current = read(OUT);
  } catch {
    /* missing */
  }
  if (current !== output) {
    console.error(`${OUT} is out of date. Run: npm run build`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date.`);
} else {
  writeFileSync(path.join(root, OUT), output);
  console.log(`Wrote ${OUT} (${nodes.length} nodes, ${(output.length / 1024).toFixed(0)} KB)`);
}
